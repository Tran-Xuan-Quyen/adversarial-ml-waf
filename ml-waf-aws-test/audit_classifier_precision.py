#!/usr/bin/env python3
"""
audit_classifier_precision.py
-----------------------------
Independent Ground-Truth & Classifier Precision Audit for AWS WAF probe results.

Methodological Improvements:
  1. Non-Circular Independent Ground Truth:
     - Data Extraction (200 OK): Validates against NestJS entity schema (projectName, applicationDomain).
     - Database Layer Reach (500): Validates against native PostgreSQL driver error signatures.
     - Application Origin Reach (400/422): Validates against NestJS exception envelope schema
       (JSON envelope with statusCode and message/error keys), completely independent of
       the probe classifier's substring needles.
     - Edge / WAF Blocks: Validates via HTTP 403 status, CloudFront/ALB HTML template, and AWS headers.
  2. Header Inspection: Audits 'x-amzn-errortype' and 'x-amzn-waf-action' recorded in JSONL.
  3. Interactive Review Mode: Use '--interactive' to visually review sampled records
     with fully functional override handlers ('y', 'b', 'w', 'o', 'n').

Usage:
    python audit_classifier_precision.py [--sample-size 50] [--interactive] [--jsonl data/aws_probe_results.jsonl]
"""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import random
import re
import sys

DATA_DIR = Path(__file__).resolve().parent / "data"
DEFAULT_JSONL = DATA_DIR / "aws_probe_results.jsonl"
OUTPUT_REPORT = DATA_DIR / "classifier_precision_audit.txt"

# Native PostgreSQL error markers that unequivocally prove request executed in Postgres
PG_ERROR_MARKERS = (
    "syntax error at or near",
    "unterminated quoted string",
    "column \"",
    "does not exist",
    "operator does not exist",
    "invalid input syntax for",
    "failed to fetch projects",
    "failed to fetch project",
    "division by zero",
    "character with byte sequence",
    "invalid byte sequence",
)


def is_valid_nestjs_validation_envelope(body: str, status_code: int) -> bool:
    """
    Independent structural schema check for NestJS exception envelope.
    Verifies that the response originated from NestJS application layer
    (ValidationPipe, ParseIntPipe, or DTO exception), NOT from edge/WAF.
    Non-circular: does not rely on specific error message strings.
    """
    if not body:
        return False
    b_low = body.strip().lower()
    if b_low.startswith("<!doctype") or "<html" in b_low[:150] or "<head" in b_low[:150]:
        return False

    try:
        data = json.loads(body)
        if isinstance(data, dict):
            has_code = "statuscode" in [k.lower() for k in data.keys()] or data.get("statusCode") in (400, 422, status_code)
            has_msg = "message" in data or "error" in data
            return bool(has_code and has_msg)
    except Exception:
        if '"statuscode":' in b_low and ('"message":' in b_low or '"error":' in b_low):
            return True
    return False


def independent_ground_truth(rec: dict) -> dict:
    """
    Independent ground truth evaluation without relying on probe classifier needles.
    Returns: {
        'status': int,
        'variant': str,
        'claimed_result': str,
        'claimed_detail': str,
        'true_category': str,
        'is_false_positive_block': bool,
        'is_false_negative_bypass': bool,
        'reason': str
    }
    """
    http_status = rec.get("http_status")
    result = rec.get("result")
    detail = rec.get("result_detail", "")
    body = (rec.get("body_snip") or "").lower()
    headers = {k.lower(): str(v).lower() for k, v in rec.get("headers", {}).items()}

    # Tier 1: Check AWS WAF / Edge Header Indicators
    has_waf_header = (
        "x-amzn-errortype" in headers
        or headers.get("x-amzn-waf-action") in ("block", "captcha", "challenge")
    )
    is_alb_cloudfront_html = (
        "<title>403 forbidden</title>" in body
        or "request could not be satisfied" in body
        or "generated by cloudfront" in body
        or "request blocked by" in body
    )

    # Tier 2: Check NestJS Application Layer Data Leak (HTTP 200)
    has_nestjs_project_entity = False
    if http_status == 200:
        if (
            ('"projectname"' in body or '"applicationdomain"' in body)
            and '"statuscode":' not in body
            and not is_alb_cloudfront_html
        ):
            has_nestjs_project_entity = True

    # Tier 3: Check PostgreSQL Execution in Backend (HTTP 500)
    has_pg_error = False
    if http_status == 500:
        if any(marker in body for marker in PG_ERROR_MARKERS):
            has_pg_error = True

    # Tier 4: Check Application Origin Validation (HTTP 400 / 422) via NestJS envelope
    has_app_validation = False
    if http_status in (400, 422):
        if not is_alb_cloudfront_html and is_valid_nestjs_validation_envelope(rec.get("body_snip") or "", http_status):
            has_app_validation = True

    # Determine True Category
    if http_status in (403, 406, 429) or has_waf_header or is_alb_cloudfront_html:
        true_category = "waf_blocked"
    elif http_status == 200 and has_nestjs_project_entity:
        true_category = "db_exploit_200"
    elif http_status == 500 and has_pg_error:
        true_category = "db_error_500"
    elif http_status in (400, 422) and has_app_validation:
        true_category = "app_origin_400"
    elif http_status == 404:
        true_category = "app_not_found"
    elif http_status in (502, 503, 504):
        true_category = "upstream_error"
    else:
        true_category = "other"

    # Evaluate Misclassification
    fp_block = False
    fn_bypass = False
    reason = "Consistent"

    if result == "blocked" and true_category in ("db_exploit_200", "db_error_500", "app_origin_400"):
        fp_block = True
        reason = f"False Positive Block: Claimed blocked, but payload reached {true_category}."
    elif result == "bypass" and true_category == "waf_blocked":
        fn_bypass = True
        reason = "False Negative Bypass: Claimed bypass, but response is edge/WAF block."

    return {
        "status": http_status,
        "variant": rec.get("variant", "unknown"),
        "claimed_result": result,
        "claimed_detail": detail,
        "true_category": true_category,
        "is_false_positive_block": fp_block,
        "is_false_negative_bypass": fn_bypass,
        "reason": reason,
        "body_snip": body[:120],
        "headers": headers,
    }


def review_record_interactively(r: dict, auto_eval: dict) -> dict:
    """Handle interactive human review with fully functional override logic (Fix P0 Item 2)."""
    claimed_res = r.get("result", "other")
    claimed_det = r.get("result_detail", "")

    print(f"\nVariant: {r.get('variant')}  Status: {r.get('http_status')}")
    print(f"  Claimed: Result={claimed_res.upper()} (detail: {claimed_det})")
    print(f"  Auto-Evaluation: {auto_eval['true_category']} ({auto_eval['reason']})")
    print(f"  URL: {r.get('url_snip')}")
    print(f"  Body snippet: {r.get('body_snip')}")
    print(f"  Headers: {r.get('headers', {})}")

    while True:
        prompt = (
            "  Confirm classification?\n"
            "    [Enter / y] Confirm auto-evaluation as ground truth\n"
            "    [b] Override: True status is BYPASS (request passed WAF)\n"
            "    [w] Override: True status is BLOCKED (WAF/Edge rejection)\n"
            "    [o] Override: True status is OTHER (404, 502, network error)\n"
            "    [n] Disagree / Select specific category from menu\n"
            "  Your choice: "
        )
        choice = input(prompt).strip().lower()

        if choice in ("", "y", "yes"):
            true_cat = auto_eval["true_category"]
            break
        elif choice == "b":
            b_type = input("    Bypass category: [1] 200 Data Leak, [2] 500 DB Error, [3] 400/422 Origin Reach (default 1): ").strip()
            if b_type == "2":
                true_cat = "db_error_500"
            elif b_type == "3":
                true_cat = "app_origin_400"
            else:
                true_cat = "db_exploit_200"
            break
        elif choice == "w":
            true_cat = "waf_blocked"
            break
        elif choice == "o":
            true_cat = "other"
            break
        elif choice == "n":
            cat_choice = input("    Select Category: [1] WAF Block, [2] 200 Data Leak, [3] 500 DB Error, [4] 400 Origin Reach, [5] 404, [6] 502/Other: ").strip()
            cat_map = {
                "1": "waf_blocked",
                "2": "db_exploit_200",
                "3": "db_error_500",
                "4": "app_origin_400",
                "5": "app_not_found",
                "6": "other",
            }
            if cat_choice in cat_map:
                true_cat = cat_map[cat_choice]
                break
            print("    [!] Invalid selection, please enter 1-6.")
        else:
            print("    [!] Invalid choice. Please enter y, b, w, o, or n.")

    # Re-evaluate discrepancy based on confirmed true_cat
    is_true_waf = (true_cat == "waf_blocked")
    is_true_bypass = (true_cat in ("db_exploit_200", "db_error_500", "app_origin_400"))

    fp_block = (claimed_res == "blocked" and not is_true_waf)
    fn_bypass = (claimed_res == "bypass" and not is_true_bypass)

    auto_eval["true_category"] = true_cat
    auto_eval["is_false_positive_block"] = fp_block
    auto_eval["is_false_negative_bypass"] = fn_bypass
    auto_eval["human_reviewed"] = True
    if fp_block:
        auto_eval["reason"] = f"Human Override: False Positive Block (Confirmed as {true_cat})"
    elif fn_bypass:
        auto_eval["reason"] = f"Human Override: False Negative Bypass (Confirmed as {true_cat})"
    else:
        auto_eval["reason"] = f"Human Confirmed: Consistent ({true_cat})"

    return auto_eval


def main():
    ap = argparse.ArgumentParser(description="Independent Ground-Truth & Classifier Precision Audit")
    ap.add_argument("--jsonl", type=Path, default=DEFAULT_JSONL)
    ap.add_argument("--sample-size", type=int, default=50, help="Samples per category (default: 50)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--interactive", action="store_true", help="Launch interactive human review mode")
    ns = ap.parse_args()

    if not ns.jsonl.exists():
        print(f"File not found: {ns.jsonl}", file=sys.stderr)
        return 1

    records_by_cat = defaultdict(list)
    total_records = 0

    with open(ns.jsonl, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
                total_records += 1
                res = rec.get("result", "other")
                det = rec.get("result_detail", "")
                cat_key = f"{res}_{det}" if det else res
                records_by_cat[cat_key].append(rec)
            except json.JSONDecodeError:
                pass

    print(f"Loaded {total_records:,} records across {len(records_by_cat)} categories.")

    rng = random.Random(ns.seed)
    sampled_evals = []
    category_summary = {}

    for cat, recs in sorted(records_by_cat.items()):
        sample = rng.sample(recs, min(len(recs), ns.sample_size))

        if ns.interactive:
            print(f"\n--- Interactive Review for category '{cat}' ({len(sample)} samples) ---")
            cat_evals = []
            for i, r in enumerate(sample, 1):
                auto_eval = independent_ground_truth(r)
                print(f"\n[{i}/{len(sample)}]")
                reviewed = review_record_interactively(r, auto_eval)
                cat_evals.append(reviewed)
        else:
            cat_evals = [independent_ground_truth(r) for r in sample]

        sampled_evals.extend(cat_evals)

        fp_count = sum(1 for e in cat_evals if e["is_false_positive_block"])
        fn_count = sum(1 for e in cat_evals if e["is_false_negative_bypass"])
        correct = len(cat_evals) - fp_count - fn_count
        precision = (correct / len(cat_evals) * 100) if cat_evals else 100.0

        category_summary[cat] = {
            "total_in_dataset": len(recs),
            "sampled": len(sample),
            "correct": correct,
            "false_positives": fp_count,
            "false_negatives": fn_count,
            "precision": precision,
        }

    total_sampled = len(sampled_evals)
    total_correct = sum(
        1 for e in sampled_evals if not e["is_false_positive_block"] and not e["is_false_negative_bypass"]
    )
    overall_precision = (total_correct / total_sampled * 100) if total_sampled else 100.0
    total_fp = sum(1 for e in sampled_evals if e["is_false_positive_block"])
    total_fn = sum(1 for e in sampled_evals if e["is_false_negative_bypass"])

    lines = [
        "=" * 80,
        "  INDEPENDENT GROUND-TRUTH & CLASSIFIER PRECISION AUDIT REPORT",
        "=" * 80,
        f"Input File:        {ns.jsonl.name} ({total_records:,} total records)",
        f"Sampled Records:   {total_sampled} (seed={ns.seed}, max {ns.sample_size}/category)",
        f"Mode:              {'Interactive Human Review' if ns.interactive else 'Automated Structural Audit'}",
        f"Overall Precision: {overall_precision:.2f}% ({total_correct}/{total_sampled} verified correct)",
        f"Total False Pos:   {total_fp} (App error misclassified as WAF block)",
        f"Total False Neg:   {total_fn} (WAF block misclassified as Bypass)",
        "-" * 80,
        f"{'Category':<28} {'Total':>8} {'Sampled':>8} {'Correct':>8} {'FP':>5} {'FN':>5} {'Precision':>10}",
        "-" * 80,
    ]

    for cat, s in category_summary.items():
        lines.append(
            f"{cat:<28} {s['total_in_dataset']:>8,} {s['sampled']:>8} {s['correct']:>8} {s['false_positives']:>5} {s['false_negatives']:>5} {s['precision']:>9.1f}%"
        )

    lines.extend([
        "=" * 80,
        "",
        "Methodology & Ground-Truth Verification Description for Paper:",
        "  1. Non-Circular Independent Ground Truth:",
        "     - Data Extraction (200 OK): Verified against backend NestJS Project Schema (projectName, applicationDomain).",
        "     - Database Layer Reach (500): Verified against native PostgreSQL driver exception syntax.",
        "     - Origin Validation Reach (400/422): Verified via NestJS JSON exception envelope structure (statusCode/message).",
        "     - Edge / WAF Blocks: Verified via HTTP 403 status, CloudFront/ALB HTML template, and AWS headers.",
        f"  2. Results: Independent inspection of N={total_sampled} randomly sampled probe responses",
        f"     yields an empirical classifier precision of {overall_precision:.2f}% with {total_fp} false positive(s) and {total_fn} false negative(s).",
        "",
    ])

    report_text = "\n".join(lines)
    print(report_text)
    OUTPUT_REPORT.write_text(report_text, encoding="utf-8")
    print(f"[OK] Audit report saved to {OUTPUT_REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
